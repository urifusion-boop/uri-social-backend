def _pick_mix_from_performance(
    performance: Dict[str, Any],
    industry: str,
    brand: Optional[Dict[str, Any]] = None,
    week_number: int = 0,
) -> List[str]:
    """
    Build a personalised 7-day content-type mix driven by this user's
    performance data.  Falls back to the industry/default mix when there
    is no historical data.
    """
    if not performance or not performance.get("has_data"):
        return _pick_mix(industry, week_number)

    avg_by_topic: Dict[str, float] = performance.get("avg_engagement_by_topic", {})
    if not avg_by_topic:
        return _pick_mix(industry, week_number)

    # Map each measured topic → content_type and accumulate weighted scores
    type_scores: Dict[str, float] = {t: 0.0 for t in CONTENT_TYPES}
    for topic, eng in avg_by_topic.items():
        ct = _TOPIC_TO_CONTENT_TYPE.get(topic.lower(), "relatable")
        type_scores[ct] = max(type_scores[ct], eng)  # take the best topic score per type

    # Boost based on brand primary_goal
    primary_goal = ((brand or {}).get("primary_goal") or "").lower()
    if "sales" in primary_goal or "revenue" in primary_goal or "convert" in primary_goal:
        type_scores["promotional"] = type_scores["promotional"] * 1.5 + 0.1
    elif "community" in primary_goal or "relationship" in primary_goal:
        type_scores["relatable"] = type_scores["relatable"] * 1.4 + 0.1
        type_scores["behind_the_scenes"] = type_scores["behind_the_scenes"] * 1.3 + 0.1
    elif "awareness" in primary_goal or "audience" in primary_goal or "grow" in primary_goal:
        type_scores["educational"] = type_scores["educational"] * 1.4 + 0.1
        type_scores["engagement"] = type_scores["engagement"] * 1.2 + 0.1

    # Always ensure every type has a non-zero floor so it can appear
    for ct in CONTENT_TYPES:
        if type_scores[ct] == 0.0:
            type_scores[ct] = 0.5

    # Distribute 7 slots proportionally to scores, minimum 1 slot per type
    total_score = sum(type_scores.values()) or 1.0
    raw_slots = {ct: max(1, round((s / total_score) * 7)) for ct, s in type_scores.items()}

    # Adjust to exactly 7 slots
    while sum(raw_slots.values()) > 7:
        # Remove a slot from the lowest-scoring over-allocated type
        excess = [(ct, raw_slots[ct]) for ct in raw_slots if raw_slots[ct] > 1]
        excess.sort(key=lambda x: type_scores[x[0]])
        raw_slots[excess[0][0]] -= 1
    while sum(raw_slots.values()) < 7:
        # Add a slot to the highest-scoring type
        best = max(type_scores, key=type_scores.get)
        raw_slots[best] += 1

    # Build ordered 7-day list: spread types across the week sensibly
    # Order: educational early week, promotional mid-week, engagement/relatable end
    day_type_order = ["educational", "relatable", "educational", "promotional",
                      "behind_the_scenes", "engagement", "relatable"]
    mix: List[str] = []
    remaining = dict(raw_slots)
    for preferred in day_type_order:
        if remaining.get(preferred, 0) > 0:
            mix.append(preferred)
            remaining[preferred] -= 1
        else:
            # Pick the type with most remaining slots
            fallback = max(remaining, key=lambda k: remaining[k])
            mix.append(fallback)
            remaining[fallback] -= 1

    print(f"[Calendar] Personalised mix from performance: {mix} (scores: {type_scores})")
    return mix


def _compute_mix_ratios(mix: List[str]) -> Dict[str, float]:
    counts: Dict[str, int] = {t: 0 for t in CONTENT_TYPES}
    for t in mix:
        counts[t] = counts.get(t, 0) + 1
    total = len(mix) or 7
    return {t: round(c / total, 2) for t, c in counts.items()}


# ── Completeness / coherence validation ────────────────────────────────────────
# Deterministic check run on every AI-generated day before it's ever shown to a
# user. A calendar entry that promises "3 things" but only gives a 2-sentence
# description, or a CTA/caption direction with no real content, is not usable —
# this catches that class of problem and drives one retry with the specific
# failures listed back to the model, rather than silently shipping an incomplete
# entry.

VIDEO_FORMATS = {
    "talking_head", "product_demo", "testimonial",
    "tutorial", "behind_the_scenes", "trend_based",
}

_NUMBER_WORDS = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5,
    "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10,
}


def _extract_promised_count(title: str) -> Optional[int]:
    """If a title promises a specific count ("Three things...", "5 ways...",
    "Top 4 mistakes"), return that count so key_points can be checked against
    it. None if the title doesn't make a countable claim."""
    t = title.lower()
    digit_match = re.search(r"\b(\d{1,2})\b", t)
    if digit_match:
        n = int(digit_match.group(1))
        if 2 <= n <= 10:
            return n
    for word, n in _NUMBER_WORDS.items():
        if n >= 2 and re.search(rf"\b{word}\b", t):
            return n
    return None


def _validate_day(idea: Dict[str, Any]) -> List[str]:
    """Return a list of human-readable completeness/coherence failures for one
    AI-generated day; an empty list means the day is usable as-is."""
    issues: List[str] = []
    title = str(idea.get("title") or "").strip()
    if not title:
        issues.append("title is empty")

    hook = str(idea.get("hook") or "").strip()
    if len(hook) < 10:
        issues.append("hook is missing or too short — must be an actual opening line")

    key_points = idea.get("key_points")
    if not isinstance(key_points, list) or len(key_points) < 2:
        issues.append("key_points must be a list of at least 2 concrete points")
    else:
        thin = [p for p in key_points if len(str(p).strip()) < 15]
        if thin:
            issues.append(f"{len(thin)} key_point(s) are too thin to be usable")
        promised = _extract_promised_count(title)
        if promised and len(key_points) < promised:
            issues.append(
                f"title implies {promised} points but only {len(key_points)} key_points were given"
            )

    caption_direction = str(idea.get("caption_direction") or "").strip()
    if len(caption_direction) < 15:
        issues.append("caption_direction is missing or too short")

    keywords = idea.get("keywords")
    if not isinstance(keywords, list) or len(keywords) < 1:
        issues.append("keywords must have at least 1 entry")

    if not str(idea.get("cta") or "").strip():
        issues.append("cta is empty")

    video_idea = idea.get("video_idea")
    if not isinstance(video_idea, dict):
        issues.append("video_idea is missing")
    else:
        if video_idea.get("format") not in VIDEO_FORMATS:
            issues.append(
                f"video_idea.format {video_idea.get('format')!r} is not a recognised format — "
                f"it MUST be exactly one of: {', '.join(sorted(VIDEO_FORMATS))} (no other wording, no synonyms)"
            )
        if len(str(video_idea.get("hook") or "").strip()) < 10:
            issues.append("video_idea.hook is missing or too short")
        if not video_idea.get("talking_points"):
            issues.append("video_idea.talking_points is empty")
        if not video_idea.get("scenes"):
            issues.append("video_idea.scenes is empty")
        if not str(video_idea.get("cta") or "").strip():
            issues.append("video_idea.cta is empty")

    return issues


