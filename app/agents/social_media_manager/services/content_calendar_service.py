async def generate_plan(
    user_id: str,
    platforms: List[str],
    brand: Dict[str, Any],
    db: AsyncIOMotorDatabase,
    force: bool = False,
    brand_id: Optional[str] = None,
) -> Dict[str, Any]:
    now = datetime.utcnow()
    monday = _get_monday(now)
    week_start = monday.strftime("%Y-%m-%d")
    scope = _cal_scope(user_id, brand_id)

    previous_titles: List[str] = []
    previous_key_points: List[str] = []

    if force:
        # Grab current week's titles so AI doesn't regenerate the same ideas
        existing_active = await get_active_plan(user_id, db, week_start, brand_id=brand_id)
        if existing_active:
            previous_titles = [d.get("title", "") for d in existing_active.get("days", []) if d.get("title")]
        await db[COLLECTION].update_many(
            {**scope, "week_start": week_start, "status": "active"},
            {"$set": {"status": "archived"}},
        )
        # Bust all v2 trend cache entries for this industry so we get fresh keywords
        industry_temp = brand.get("industry", "")
        if industry_temp:
            try:
                await db["trends_cache"].delete_many(
                    {"_id": {"$regex": f"^v2:{re.escape(industry_temp.lower())}:"}}
                )
                print(f"[Calendar] Busted trend cache for '{industry_temp}' on force-regenerate")
            except Exception:
                pass
    else:
        existing = await get_active_plan(user_id, db, week_start, brand_id=brand_id)
        if existing:
            return existing

    industry = brand.get("industry", "")

    # Collect titles from last 4 weeks to prevent idea repetition
    for weeks_ago in range(1, 5):
        past_monday = (monday - timedelta(days=7 * weeks_ago)).strftime("%Y-%m-%d")
        past_plan = await db[COLLECTION].find_one(
            {**scope, "week_start": past_monday},
            {"_id": 0, "days": 1},
        )
        if past_plan:
            previous_titles += [d.get("title", "") for d in past_plan.get("days", []) if d.get("title")]
            for d in past_plan.get("days", []):
                previous_key_points += [str(p) for p in (d.get("key_points") or []) if p]

    # ── Data signals ──────────────────────────────────────────────────────────
    performance = await PerformanceAnalyticsService.get_user_performance(user_id, db)
    trend_keywords = await TrendDataService.get_trending_keywords(industry, db=db)

    # ── Enhanced PRD signals ──────────────────────────────────────────────────
    # Holidays & seasonal events (PRD Section 8)
    region = brand.get("region", "")
    upcoming_holidays = HolidayCalendarService.get_upcoming_holidays(week_start, region, industry)

    # Cultural moments & trending topics (PRD Section 7)
    trending_topics = CulturalMomentService.get_trending_topics(industry, region, week_start)
    cultural_moments = CulturalMomentService.get_cultural_moments(week_start, region)

    # Industry best practices (PRD Section 6)
    industry_best_practices = IndustryTrendService.get_industry_best_practices(industry)
    industry_trending = IndustryTrendService.get_trending_topics(industry)

    # ── Personalised content mix from performance data ────────────────────────
    week_number = monday.isocalendar()[1]
    if force:
        # On regenerate, pick a random variant + rotation so the type layout
        # genuinely changes (same week → same week_number, so we must randomise)
        variant_idx = secrets.randbelow(len(DEFAULT_MIX_VARIANTS))
        base = DEFAULT_MIX_VARIANTS[variant_idx][:]
        rotation = secrets.randbelow(6) + 1  # always rotate at least 1 slot
        mix = base[rotation:] + base[:rotation]
        print(f"[Calendar] Force-regen: variant={variant_idx} rotation={rotation} → mix={mix}")
    else:
        mix = _pick_mix_from_performance(performance, industry, brand, week_number=week_number)
        print(f"[Calendar] Week {week_number} → mix={mix}")

    generation_method = "ai"  # default fallback
    days: List[Dict[str, Any]] = []

    # ── AI generation (always used — grounded in trend + performance signals) ─
    _ai_error: Optional[str] = None
    try:
        if trend_keywords or performance.get("has_data"):
            generation_method = "data_driven" if performance.get("has_data") else "trend_driven"
        ai_ideas = await _generate_ideas(
            brand, mix, week_start, platforms,
            previous_titles=previous_titles,
            previous_key_points=previous_key_points,
            trend_keywords=trend_keywords or [],
            performance=performance,
            force=force,
        )
    except Exception as exc:
        import traceback as _tb
        _ai_error = str(exc)
        print(f"[Calendar] AI generation failed: {exc}\n{_tb.format_exc()}")
        ai_ideas = []

    for i, idea in enumerate(ai_ideas):
        day_date = (monday + timedelta(days=i)).strftime("%Y-%m-%d")
        day_of_week = (monday + timedelta(days=i)).strftime("%A")
        content_type = mix[i]
        title = idea.get("title", "")

        # Score against real signals for transparency
        kw = idea.get("keyword", "")
        trend_score = 0
        perf_score = 0
        if trend_keywords:
            match = next((t for t in trend_keywords if t["keyword"].lower() in title.lower()), None)
            if match:
                trend_score = match.get("trend_score", 0)
        if performance.get("has_data"):
            top_topics = performance.get("top_topics", [])
            title_lower = title.lower()
            if any(t.lower() in title_lower for t in top_topics):
                perf_score = 75

        # ── Enhanced PRD fields ───────────────────────────────────────────────
        # hook/key_points/caption_direction/keywords/cta/video_idea are now
        # generated by the SAME AI call as the title (see _generate_ideas) —
        # they're read straight off the idea rather than derived afterward,
        # since that's what makes them coherent with this specific idea.
        primary_goal = brand.get("primary_goal", "engagement")

        # Enhanced explanation with data backing (PRD Output requirement)
        enhanced_reason = ContentExplainerService.explain_recommendation(
            content_type=content_type,
            topic=title,
            post_day=day_of_week,
            primary_goal=primary_goal,
            historical_performance=performance if performance.get("has_data") else None,
            upcoming_holidays=upcoming_holidays,
            trending_topics=trending_topics + industry_trending,
            industry_best_practices=industry_best_practices,
        )

        # Deterministic (Nigeria/global) holidays for this date, plus whatever the AI
        # itself identified as relevant for the brand's own region this week (req 4) —
        # merged into the same list so the frontend's existing holiday badge just works
        # for every country, not only the ones HolidayCalendarService has hardcoded.
        day_holidays = [h for h in upcoming_holidays if h["date"] == day_date] if upcoming_holidays else []
        ai_holiday = idea.get("holiday_reference")
        if isinstance(ai_holiday, dict) and str(ai_holiday.get("name") or "").strip():
            ai_holiday_name = str(ai_holiday["name"]).strip()
            if not any(h.get("name", "").strip().lower() == ai_holiday_name.lower() for h in day_holidays):
                day_holidays.append({
                    "date": day_date,
                    "name": ai_holiday_name,
                    "type": "ai_suggested",
                    "relevance_score": 90,
                    "content_angle": str(ai_holiday.get("why_relevant") or "").strip(),
                })

        days.append({
            "day_index":           i,
            "date":                day_date,
            "day_of_week":         day_of_week,
            "content_type":        content_type,
            "title":               title,
            "description":         idea.get("description", ""),
            "keyword":             kw,
            "trend_score":         trend_score,
            "performance_score":   perf_score,
            "format_score":        0,
            "final_score":         round((trend_score * 0.4) + (perf_score * 0.4), 1),
            "reason":              enhanced_reason,
            "format":              idea.get("assigned_format") or (performance.get("top_formats") or ["image"])[0],
            "platforms":           platforms,
            # Coherent per-idea fields (all from the same AI call as title/description)
            "hook":                idea.get("hook", ""),
            "key_points":          idea.get("key_points", []),
            "caption_direction":   idea.get("caption_direction", ""),
            "keywords":            idea.get("keywords", []),
            "cta":                 idea.get("cta", ""),
            "video_idea":          idea.get("video_idea", {}),
            "upcoming_holidays":   day_holidays,
            "trending_topics":     trending_topics[:3] if trending_topics else [],
            "acted_on":            False,
            "acted_on_draft_ids":  [],
            "regenerated_count":   0,
            "last_regenerated_at": None,
        })

    # Guard: if both pipelines failed, restore the archived plan rather than
    # persisting an empty plan that would leave the user with a broken calendar.
    if not days:
        print(f"[Calendar] Both pipelines failed for user {user_id} — restoring previous plan")
        restored = await db[COLLECTION].find_one_and_update(
            {**scope, "week_start": week_start, "status": "archived"},
            {"$set": {"status": "active"}},
            sort=[("generated_at", -1)],
            return_document=True,
        )
        if restored:
            restored.pop("_id", None)
            return restored
        reason = f" Cause: {_ai_error}" if _ai_error else ""
        raise RuntimeError(f"Content generation failed and no previous plan to restore.{reason}")

    plan_id = str(uuid.uuid4())
    doc = {
        "plan_id":          plan_id,
        "user_id":          user_id,
        "brand_id":         brand_id,
        "week_start":       week_start,
        "generated_at":     now.isoformat(),
        "status":           "active",
        "generation_method":generation_method,
        "platforms":        platforms,
        "days":             days,
        "content_mix":      _compute_mix_ratios(mix),
        "data_signals": {
            "post_count":       performance.get("post_count", 0),
            "top_topics":       performance.get("top_topics", []),
            "top_formats":      performance.get("top_formats", []),
            "trend_source":     trend_keywords[0].get("source", "none") if trend_keywords else "none",
            "trend_kw_count":   len(trend_keywords),
        },
        "brand_snapshot": {
            "brand_name":          brand.get("brand_name"),
            "industry":            brand.get("industry"),
            "tagline":             brand.get("tagline"),
            "business_description":brand.get("business_description") or brand.get("product_description"),
            "key_products_services":brand.get("key_products_services") or [],
            "brand_voice":         brand.get("brand_voice") or brand.get("derived_voice"),
            "voice_sample":        brand.get("voice_sample"),
            "platform_tones":      brand.get("platform_tones") or {},
            "same_tone_everywhere":brand.get("same_tone_everywhere", True),
            "target_audience":     brand.get("target_audience"),
            "audience_age_range":  brand.get("audience_age_range"),
            "primary_goal":        brand.get("primary_goal"),
            "region":              brand.get("region"),
            "content_pillars":     brand.get("content_pillars") or [],
            "preferred_formats":   brand.get("preferred_formats") or [],
            "cta_styles":          brand.get("cta_styles") or [],
            "guardrails":          brand.get("guardrails") or {},
            "key_dates":           brand.get("key_dates"),
            "key_dates_structured":brand.get("key_dates_structured") or [],
            "posting_cadence":     brand.get("posting_cadence"),
            "website":             brand.get("website"),
        },
    }
    await db[COLLECTION].insert_one({**doc, "_id": plan_id})
    return doc


def _build_description(idea: Dict[str, Any], brand: Dict[str, Any]) -> str:
    """Build a brief description for a data-driven idea."""
    keyword  = idea.get("keyword", "")
    industry = brand.get("industry", "business")
    audience = brand.get("target_audience", "your audience")
    reason   = idea.get("reason", "")
    desc = (
        f"A {idea.get('content_type', 'content').replace('_', ' ')} post around "
        f'"{keyword}" — a trending topic in {industry} right now. '
        f"Speak directly to {audience}."
    )
    if reason:
        desc += f" Data signal: {reason}."
    return desc


async def regenerate_day(
    plan_id: str,
    day_index: int,
    user_id: str,
    db: AsyncIOMotorDatabase,
    brand_id: Optional[str] = None,
) -> Dict[str, Any]:
    scope = _cal_scope(user_id, brand_id)
    plan = await db[COLLECTION].find_one(
        {**scope, "plan_id": plan_id},
        {"_id": 0},
    )
    if not plan:
        raise ValueError("Plan not found")

    day = next((d for d in plan["days"] if d["day_index"] == day_index), None)
    if day is None:
        raise ValueError(f"Day {day_index} not found in plan")

    brand = plan.get("brand_snapshot") or {}
    mix = [d["content_type"] for d in sorted(plan["days"], key=lambda x: x["day_index"])]
    single_mix = [mix[day_index]]

    monday = datetime.strptime(plan["week_start"], "%Y-%m-%d")
    week_start = plan["week_start"]
    platforms = plan.get("platforms") or []

    # Build a targeted prompt for just one day
    content_type = mix[day_index]
    brand_name = brand.get("brand_name") or "the brand"
    industry = brand.get("industry") or "business"
    voice = brand.get("brand_voice") or "professional and engaging"
    audience = brand.get("target_audience") or "general audience"
    platforms_str = ", ".join(platforms) if platforms else "social media"
    day_name = WEEK_DAYS[day_index]
    tagline = brand.get("tagline", "")
    description = brand.get("business_description") or brand.get("product_description", "")
    products = brand.get("key_products_services") or []
    products_str = ", ".join(products) if products else ""
    pillars = brand.get("content_pillars") or []
    pillars_str = ", ".join(pillars) if pillars else ""
    voice_sample = brand.get("voice_sample", "")
    region = brand.get("region", "")
    guardrails = brand.get("guardrails") or {}
    avoid = guardrails.get("avoid_topics") or guardrails.get("avoid") or []
    avoid_str = ", ".join(avoid) if avoid else ""

    # Avoid all existing day titles in this plan
    existing_titles = [d.get("title", "") for d in plan["days"] if d.get("title") and d["day_index"] != day_index]

    brand_line = f"{brand_name}"
    if tagline:
        brand_line += f' ("{tagline}")'
    if industry:
        brand_line += f" — {industry}"
    if description:
        brand_line += f"\nWhat they do: {description}"
    if products_str:
        brand_line += f"\nProducts/services: {products_str}"

    avoid_block = ""
    if existing_titles:
        avoid_block += "\nAlready used this week (do not repeat):\n" + "\n".join(f"- {t}" for t in existing_titles)
    if avoid_str:
        avoid_block += f"\nTopics to avoid: {avoid_str}"

    country_block = ""
    if region:
        country_block = (
            f"Country/date awareness: this brand's audience is in {region}. If a real, "
            f"well-known public holiday, awareness day, or industry date genuinely falls "
            f"near {day_name} for {region} and is relevant to this business, let it shape "
            f"the idea AND set holiday_reference below — never invent a date you're not "
            f"confident actually exists; leave holiday_reference null otherwise."
        )

    stage_block = (
        "Business stage: infer this brand's apparent stage of growth from the details "
        "above and let it inform tone where relevant (e.g. an early-stage brand benefits "
        "more from trust-building/story content, an established one can lean harder into "
        "authority/scale content)."
    )

    # Same deterministic check as _generate_ideas — if the business owner saved a
    # date that lands on THIS exact day, it's non-negotiable, not left to AI recall.
    user_date_block = ""
    day_date_str = day.get("date") or ""
    for kd in (brand.get("key_dates_structured") or []):
        label = str((kd or {}).get("label") or "").strip()
        date_str = str((kd or {}).get("date") or "").strip()
        if label and date_str and date_str == day_date_str:
            user_date_block = (
                f"MANDATORY: the business owner personally saved {day_date_str} as \"{label}\" "
                f"in their Brand Playbook — this day's idea MUST be built around it (not a general "
                f"public holiday, non-negotiable). Set holiday_reference to "
                f'{{"name": "{label}", "why_relevant": "..."}}.'
            )
            break

    base_prompt = f"""You are a senior social media strategist.

{brand_line}
Brand voice: {voice}{f' | Example: "{voice_sample[:150]}"' if voice_sample else ''}
Target audience: {audience}{f' | {region} market' if region else ''}
{f'Content pillars: {pillars_str}' if pillars_str else ''}
Platforms: {platforms_str}
{country_block}
{stage_block}
{user_date_block}
{avoid_block}

Generate ONE new, COMPLETE {CONTENT_TYPE_LABELS[content_type]} content brief for {day_name}
— a full, ready-to-publish idea, not just a title.
Make it different from the previous idea: "{day.get('title', '')}"
Be specific to this brand — use real product names, audience pain points, industry context.
Your creative lens is this specific business — its products, audience, goal, and location —
not a generic instance of "{CONTENT_TYPE_LABELS[content_type]}".

Return ONLY a valid JSON object with ALL of these fields:
{{
  "title": "max 10 words. If it makes a countable claim (e.g. '3 things'), key_points must deliver that many.",
  "hook": "the exact opening line this post would start with — real usable text, 1 sentence",
  "key_points": ["2-5 concrete, specific points a person could copy straight into the caption"],
  "description": "2-3 sentences tying the idea together — what to say, who it speaks to, why it matters now",
  "caption_direction": "1-2 sentences of specific guidance for writing this exact caption",
  "keywords": ["2-4 real keywords/hashtag-worthy terms specific to this idea"],
  "cta": "one specific call-to-action sentence that fits this exact idea",
  "video_idea": {{
    "format": "one of talking_head | product_demo | testimonial | tutorial | behind_the_scenes | trend_based",
    "hook": "exact opening line for the video",
    "talking_points": ["2-4 concrete things to say on camera, in order"],
    "scenes": ["2-4 concrete shots/scenes to film"],
    "cta": "the spoken/on-screen CTA for the video"
  }},
  "holiday_reference": null or {{"name": "the real holiday/date name", "why_relevant": "1 sentence on why it fits this business"}}
}}

hook, key_points, caption_direction, keywords, and cta must all clearly belong to the
SAME idea — they must cohere as one thought, not read like separate templates stitched together.
"""

    async def _call_and_parse(full_prompt: str) -> Dict[str, Any]:
        ai_request = AIService.build_ai_model(
            messages=[{"role": "user", "content": full_prompt}],
            temperature=0.9,
        )
        response = await AIService.chat_completion(ai_request)
        if isinstance(response, dict) and response.get("error"):
            raise ValueError(response["error"])

        raw_text = response.choices[0].message.content.strip()
        if raw_text.startswith("```"):
            raw_text = raw_text.split("```")[1]
            if raw_text.startswith("json"):
                raw_text = raw_text[4:]
        return json.loads(raw_text.strip())

    correction_block = ""
    new_idea: Dict[str, Any] = {}
    for attempt in range(2):
        new_idea = await _call_and_parse(base_prompt + correction_block)
        issues = _validate_day(new_idea)
        if not issues:
            break
        print(f"[Calendar] regenerate_day validation failed on attempt {attempt + 1}: {issues}", flush=True)
        if attempt == 0:
            correction_block = (
                "\n\n=== FIX THESE SPECIFIC PROBLEMS FROM YOUR PREVIOUS ATTEMPT ===\n"
                + "; ".join(issues)
                + "\n==================================================================="
            )

    # Deterministic holidays for this specific date, merged with whatever the AI itself
    # identified as relevant for the brand's region this time (req 4) — same merge
    # pattern as generate_plan, so a regenerated day still gets full holiday coverage.
    day_date = day.get("date") or (monday + timedelta(days=day_index)).strftime("%Y-%m-%d")
    day_holidays = [
        h for h in HolidayCalendarService.get_upcoming_holidays(week_start, region, industry)
        if h["date"] == day_date
    ]
    ai_holiday = new_idea.get("holiday_reference")
    if isinstance(ai_holiday, dict) and str(ai_holiday.get("name") or "").strip():
        ai_holiday_name = str(ai_holiday["name"]).strip()
        if not any(h.get("name", "").strip().lower() == ai_holiday_name.lower() for h in day_holidays):
            day_holidays.append({
                "date": day_date,
                "name": ai_holiday_name,
                "type": "ai_suggested",
                "relevance_score": 90,
                "content_angle": str(ai_holiday.get("why_relevant") or "").strip(),
            })

    now = datetime.utcnow()
    await db[COLLECTION].update_one(
        {**scope, "plan_id": plan_id},
        {
            "$set": {
                f"days.{day_index}.title": new_idea.get("title", ""),
                f"days.{day_index}.description": new_idea.get("description", ""),
                f"days.{day_index}.hook": new_idea.get("hook", ""),
                f"days.{day_index}.key_points": new_idea.get("key_points", []),
                f"days.{day_index}.caption_direction": new_idea.get("caption_direction", ""),
                f"days.{day_index}.keywords": new_idea.get("keywords", []),
                f"days.{day_index}.cta": new_idea.get("cta", ""),
                f"days.{day_index}.video_idea": new_idea.get("video_idea", {}),
                f"days.{day_index}.upcoming_holidays": day_holidays,
                f"days.{day_index}.regenerated_count": day.get("regenerated_count", 0) + 1,
                f"days.{day_index}.last_regenerated_at": now.isoformat(),
            }
        },
    )

    updated = await db[COLLECTION].find_one({**scope, "plan_id": plan_id}, {"_id": 0})
    return updated


