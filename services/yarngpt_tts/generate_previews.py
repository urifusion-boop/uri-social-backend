"""
Make the voice-picker preview clips from the running YarnGPT service.

Customers press a play button next to each Nigerian voice before choosing it. Those clips must be
YarnGPT's own output (what the video will actually use), not a sample of something else, so they
are generated by the same service the videos use and saved as static files for the frontend.

    python -m services.yarngpt_tts.generate_previews \
        --url https://<service> --token <TTS_TOKEN> --out ../uri-social-frontent-next/public/voice-previews

Writes one <name>.wav per voice (idera.wav, jude.wav, ...). Voices that fail are listed at the end
and the exit code is 1, so a half-finished set is never mistaken for a full one.
"""
import argparse
import sys
from pathlib import Path

import httpx

from app.agents.social_media_manager.services.yarngpt_tts_service import YARNGPT_SPEAKERS


def preview_line(display_name: str) -> str:
    # About 15 words: long enough to hear the voice, and the same length the video scenes use.
    return (f"Hello, my name is {display_name}. I help small businesses in Nigeria "
            f"post, reply and run ads without stress.")


def filename_for(speaker: str) -> str:
    return f"{speaker}.wav"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", required=True)
    ap.add_argument("--token", default="")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    headers = {"Authorization": f"Bearer {args.token}"} if args.token else {}
    failed = []
    for label, speaker in YARNGPT_SPEAKERS.items():
        name = speaker.capitalize()
        try:
            resp = httpx.post(
                args.url.rstrip("/") + "/synthesize", headers=headers, timeout=300,
                json={"text": preview_line(name), "speaker": speaker, "lang": "english"},
            )
            if resp.status_code != 200 or resp.content[:4] != b"RIFF":
                raise RuntimeError(f"{resp.status_code} {resp.text[:120]}")
            (out / filename_for(speaker)).write_bytes(resp.content)
            print(f"ok      {label:22s} -> {filename_for(speaker)} ({len(resp.content) // 1024} KB)")
        except Exception as e:
            failed.append(label)
            print(f"FAILED  {label:22s} {e}")
    if failed:
        print(f"\n{len(failed)} voice(s) failed: {', '.join(failed)}")
        return 1
    print(f"\nAll {len(YARNGPT_SPEAKERS)} previews written to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
